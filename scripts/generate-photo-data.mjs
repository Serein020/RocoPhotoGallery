import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, '..');

const photosDirectory = path.join(
	projectRoot,
	'public',
	'photos',
	'pics',
);

const outputDirectory = path.join(
	projectRoot,
	'src',
	'data',
);

const outputFile = path.join(
	outputDirectory,
	'generated-photos.ts',
);

const supportedExtensions = new Set([
	'.png',
	'.jpg',
	'.jpeg',
	'.webp',
	'.gif',
]);

function parsePhotoFile(filename) {
	const extension = path.extname(filename).toLowerCase();

	if (!supportedExtensions.has(extension)) {
		return null;
	}

	const id = path.basename(filename, extension);

	/*
	 * 文件名格式：
	 *
	 * YYYYMMDD-XXX
	 *
	 * 例如：
	 * 20260918-001
	 */
	const match = id.match(
		/^(\d{4})(\d{2})(\d{2})-/,
	);

	if (!match) {
		return null;
	}

	const date =
		`${match[1]}-${match[2]}-${match[3]}`;

	return {
		id,
		image: `/photos/pics/${filename}`,
		date,
	};
}

function discoverPhotos() {
	if (!fs.existsSync(photosDirectory)) {
		return [];
	}

	const files = fs
		.readdirSync(photosDirectory, {
			withFileTypes: true,
		})
		.filter((entry) => entry.isFile())
		.map((entry) => entry.name);

	return files
		.map(parsePhotoFile)
		.filter((photo) => photo !== null)
		.sort(
			(a, b) =>
				b.date.localeCompare(a.date) ||
				b.id.localeCompare(a.id),
		)
		.map((photo, index) => ({
			...photo,
			order: index + 1,
		}));
}

const photoWorks = discoverPhotos();

fs.mkdirSync(outputDirectory, {
	recursive: true,
});

const generatedContent = `/**
 * AUTO-GENERATED FILE.
 *
 * Do not edit this file manually.
 *
 * Generated by:
 * scripts/generate-photo-data.mjs
 */

export type GeneratedPhotoWork = {
	id: string;
	image: string;
	date: string;
	order: number;
};

export const generatedPhotoWorks: GeneratedPhotoWork[] = ${JSON.stringify(
	photoWorks,
	null,
	2,
)};
`;

fs.writeFileSync(
	outputFile,
	generatedContent,
	'utf8',
);

console.log(
	`Generated ${photoWorks.length} photo(s) -> ${path.relative(
		projectRoot,
		outputFile,
	)}`,
);

