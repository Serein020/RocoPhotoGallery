import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, '..');

const photosDirectory = path.join(
	projectRoot,
	'public',
	'photos',
	'pics',
);

const outputDirectory = path.join(
	projectRoot,
	'src',
	'data',
);

const outputFile = path.join(
	outputDirectory,
	'generated-photos.ts',
);

const supportedExtensions = new Set([
	'.png',
	'.jpg',
	'.jpeg',
	'.webp',
	'.gif',
]);

function parsePhotoFile(filename) {
	const extension = path.extname(filename).toLowerCase();

	if (!supportedExtensions.has(extension)) {
		return null;
	}

	const id = path.basename(filename, extension);

	/*
	 * 文件名格式：
	 *
	 * YYYYMMDD-XXX
	 *
	 * 例如：
	 * 20260918-001
	 */
	const match = id.match(
		/^(\d{4})(\d{2})(\d{2})-/,
	);

	if (!match) {
		return null;
	}

	const date =
		`${match[1]}-${match[2]}-${match[3]}`;

	/*
	 * 当前项目的图片优化结构：
	 *
	 * 原图：
	 * /photos/pics/20260918-001.png
	 *
	 * 小图：
	 * /photos/optimized/20260918-001-small.webp
	 *
	 * 中图：
	 * /photos/optimized/20260918-001-medium.webp
	 *
	 * 大图：
	 * /photos/optimized/20260918-001-large.webp
	 *
	 * 即使优化文件暂时还没有生成，
	 * 这里也统一生成对应路径。
	 */

	const baseName = id;

	return {
		id,

		/*
		 * 原始图片
		 */
		image: `/photos/pics/${filename}`,

		/*
		 * Exhibition 卡片使用的小尺寸图片
		 */
		imageSmall:
			`/photos/optimized/${baseName}-small.webp`,

		/*
		 * Exhibition / 平板使用的中尺寸图片
		 */
		imageMedium:
			`/photos/optimized/${baseName}-medium.webp`,

		/*
		 * Lightbox 使用的大尺寸图片
		 */
		imageLarge:
			`/photos/optimized/${baseName}-large.webp`,

		date,
	};
}

function discoverPhotos() {
	if (!fs.existsSync(photosDirectory)) {
		return [];
	}

	const files = fs
		.readdirSync(photosDirectory, {
			withFileTypes: true,
		})
		.filter((entry) => entry.isFile())
		.map((entry) => entry.name);

	return files
		.map(parsePhotoFile)
		.filter((photo) => photo !== null)
		.sort(
			(a, b) =>
				b.date.localeCompare(a.date) ||
				b.id.localeCompare(a.id),
		)
		.map((photo, index) => ({
			...photo,
			order: index + 1,
		}));
}

const photoWorks = discoverPhotos();

fs.mkdirSync(outputDirectory, {
	recursive: true,
});

const generatedContent = `/** 
 * AUTO-GENERATED FILE.
 *
 * Do not edit this file manually.
 *
 * Generated by:
 * scripts/generate-photo-data.mjs
 */

export type GeneratedPhotoWork = {
\tid: string;
\timage: string;
\timageSmall: string;
\timageMedium: string;
\timageLarge: string;
\tdate: string;
\torder: number;
};

export const generatedPhotoWorks: GeneratedPhotoWork[] = ${JSON.stringify(
	photoWorks,
	null,
	2,
)};
`;

fs.writeFileSync(
	outputFile,
	generatedContent,
	'utf8',
);

console.log(
	`Generated ${photoWorks.length} photo(s) -> ${path.relative(
		projectRoot,
		outputFile,
	)}`,
);